'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { parseDateWindow, parseTimeWindow } = require('../services/communication-metrics');
const params = new URLSearchParams({from:'2026-11-10T00:25',to:'2026-11-10T00:30',direction:'all'});
const result=parseTimeWindow(params.get('from'),params.get('to'));
assert.equal(result.from,'2026-11-09T17:25:00.000Z');
assert.equal(result.to,'2026-11-09T17:30:00.000Z');
const compat=parseDateWindow(params.get('from'),params.get('to'));
assert.equal(compat.from,result.from);
assert.equal(compat.to,result.to);
const fullDay=parseDateWindow('2026-11-10','2026-11-10');
assert.equal(fullDay.from,'2026-11-09T17:00:00.000Z');
assert.equal(fullDay.to,'2026-11-10T17:00:00.000Z');
assert.throws(()=>parseTimeWindow('2026-11-10T00:30','2026-11-10T00:25'));
assert.throws(()=>parseTimeWindow('2026-11-10T00:25','2026-11-10T00:25'));
assert.throws(()=>parseDateWindow('2026-02-30','2026-02-30'));
assert.throws(()=>parseTimeWindow('2026-11-10T99:00','2026-11-11T00:00'));
const route=fs.readFileSync(path.join(__dirname,'../routes/communication.js'),'utf8');
assert.match(route,/\bparseTimeWindow\s*\(req\.query\.from,\s*req\.query\.to\)/);
assert.match(route,/router\.get\('\/:id\/metrics'/);
assert.match(route,/router\.get\('\/:id\/export\.xlsx'/);
console.log('✅ V1.7.1: timestamp WIB via query, backward compatibility, dan endpoint PDR/PLR OK');
